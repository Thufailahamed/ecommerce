import { z } from "zod";
import { SafeUrl } from "./url";
import { toolOf } from "./slots";
import { FeedOptions, FormOptions, RecommendOptions, Slot, Tool, ToastOptions } from "./tools";

export const SCHEMA_VERSION = 1 as const;

/** "restock" renders a back-in-stock email form. "toast", "inline", "feed_item" and "recommendation" belong to the toast, signup, feed and upsell tools. */
export const CampaignFormat = z.enum(["popup", "slide_in", "announcement_bar", "restock", "toast", "inline", "feed_item", "recommendation"]);
export type CampaignFormat = z.infer<typeof CampaignFormat>;

export const CampaignStatus = z.enum(["draft", "scheduled", "active", "paused", "archived"]);
export type CampaignStatus = z.infer<typeof CampaignStatus>;

export { SafeUrl } from "./url";

const HexColor = z.string().regex(/^#[0-9a-fA-F]{6}$/);

export const Placement = z.enum([
  "center", "bottom_right", "bottom_left", "top", "bottom",
]);

/** A hand-picked product shown as a card. Snapshot of title/link/image only: never price or stock, which go stale. */
export const PickedProduct = z.object({
  title: z.string().trim().min(1).max(120),
  url: SafeUrl,
  imageUrl: SafeUrl.optional(),
});
export type PickedProduct = z.infer<typeof PickedProduct>;

export const Creative = z.object({
  headline: z.string().trim().min(1).max(90),
  body: z.string().trim().max(280).default(""),
  ctaLabel: z.string().trim().min(1).max(32),
  ctaUrl: SafeUrl,
  imageUrl: SafeUrl.optional(),
  products: z.array(PickedProduct).max(3).optional(),
  /** Plain text only. The renderer must never interpret these as HTML. */
});

/**
 * A discount the merchant explicitly configures. Never generated by AI. It can only be published
 * when the store has opted in and set a maximum discount (a margin guardrail), enforced server-side.
 */
export const Promotion = z.object({
  code: z.string().trim().regex(/^[A-Za-z0-9_-]{2,32}$/, "Code may use letters, numbers, - and _"),
  percentOff: z.number().int().min(1).max(90),
  label: z.string().trim().max(60).optional(),
});
export type Promotion = z.infer<typeof Promotion>;

/** Randomised holdout: this share of consenting visitors never sees the campaign, giving a control group. */
export const Experiment = z.object({ holdoutPercent: z.number().int().min(1).max(50) });

export const Style = z.object({
  background: HexColor.default("#FFFFFF"),
  text: HexColor.default("#191A1B"),
  accent: HexColor.default("#003FFF"),
  accentText: HexColor.default("#FFFFFF"),
  radius: z.number().int().min(0).max(24).default(8),
  placement: Placement.default("center"),
});

export const Trigger = z.discriminatedUnion("type", [
  z.object({ type: z.literal("immediate") }),
  z.object({ type: z.literal("delay"), seconds: z.number().int().min(0).max(300) }),
  z.object({ type: z.literal("scroll_depth"), percent: z.number().int().min(5).max(100) }),
  z.object({ type: z.literal("exit_intent") }),
  z.object({ type: z.literal("idle"), seconds: z.number().int().min(3).max(300) }),
  /** Fires when the shopper adds something to the cart (detected by the SDK from cart requests and platform events). */
  z.object({ type: z.literal("add_to_cart"), delaySeconds: z.number().int().min(0).max(60).default(0) }),
  /** Fires once the cart subtotal reaches this amount, in store currency. */
  z.object({ type: z.literal("cart_threshold"), subtotal: z.number().positive().max(1_000_000) }),
]);

export type Trigger = z.infer<typeof Trigger>;

export const PageType = z.enum(["home", "collection", "product", "cart", "checkout", "search", "content", "other"]);
export const DeviceCategory = z.enum(["mobile", "tablet", "desktop"]);

export const Condition = z.discriminatedUnion("field", [
  z.object({ field: z.literal("page_type"), op: z.enum(["in", "not_in"]), value: z.array(PageType).min(1) }),
  z.object({ field: z.literal("url_path"), op: z.enum(["equals", "starts_with", "contains"]), value: z.string().min(1).max(200) }),
  z.object({ field: z.literal("device"), op: z.enum(["in", "not_in"]), value: z.array(DeviceCategory).min(1) }),
  z.object({ field: z.literal("cart_subtotal"), op: z.enum(["gte", "lte", "between"]), value: z.number().min(0), valueTo: z.number().min(0).optional() }),
  z.object({ field: z.literal("cart_item_count"), op: z.enum(["gte", "lte"]), value: z.number().int().min(0) }),
  z.object({ field: z.literal("product_id"), op: z.enum(["in", "not_in"]), value: z.array(z.string().min(1).max(100)).min(1).max(50) }),
  z.object({ field: z.literal("collection_id"), op: z.enum(["in", "not_in"]), value: z.array(z.string().min(1).max(100)).min(1).max(50) }),
  z.object({ field: z.literal("visitor_type"), op: z.literal("equals"), value: z.enum(["new", "returning"]) }),
  z.object({ field: z.literal("pages_viewed"), op: z.literal("gte"), value: z.number().int().min(1) }),
  z.object({ field: z.literal("product_available"), op: z.literal("equals"), value: z.boolean() }),
]);
export type Condition = z.infer<typeof Condition>;

/** One level of AND/OR over leaf conditions: deliberately shallow so every client can evaluate it identically. */
export const RuleGroup = z.object({
  match: z.enum(["all", "any"]),
  conditions: z.array(Condition).max(20),
});
export type RuleGroup = z.infer<typeof RuleGroup>;

export const Schedule = z
  .object({
    startsAt: z.string().datetime().optional(),
    endsAt: z.string().datetime().optional(),
  })
  .refine((s) => !s.startsAt || !s.endsAt || s.startsAt < s.endsAt, "endsAt must be after startsAt");

export const Frequency = z.object({
  maxImpressionsPerSession: z.number().int().min(1).max(20).default(1),
  maxImpressionsPerVisitor: z.number().int().min(1).max(100).optional(),
  suppressAfterDismissDays: z.number().min(0).max(365).default(7),
  suppressAfterClickDays: z.number().min(0).max(365).default(30),
});

export const Goal = z.object({
  type: z.enum(["clicks", "add_to_cart", "purchase", "subscribe"]),
  description: z.string().max(200).optional(),
});

/** The immutable, publishable campaign body. */
/** Formats each tool may render. A config with no `tool` is a legacy promotion (or a restock form). */
const TOOL_FORMATS: Record<Tool, readonly CampaignFormat[]> = {
  toast: ["toast"],
  feed: ["feed_item"],
  upsell: ["recommendation"],
  sms: ["popup", "slide_in", "inline", "announcement_bar"],
  email: ["popup", "slide_in", "announcement_bar", "inline", "restock"],
};

export const CampaignConfig = z.object({
  schemaVersion: z.literal(SCHEMA_VERSION),
  name: z.string().trim().min(1).max(80),
  /** Optional so every campaign saved before the multi-tool release stays valid. Use toolOf() to read it. */
  tool: Tool.optional(),
  format: CampaignFormat,
  creative: Creative,
  style: Style,
  trigger: Trigger,
  targeting: RuleGroup,
  schedule: Schedule.default({}),
  frequency: Frequency,
  priority: z.number().int().min(0).max(100).default(50),
  goal: Goal,
  promotion: Promotion.optional(),
  experiment: Experiment.optional(),
  toast: ToastOptions.optional(),
  feed: FeedOptions.optional(),
  recommend: RecommendOptions.optional(),
  form: FormOptions.optional(),
}).superRefine((c, ctx) => {
  const bad = (path: (string | number)[], message: string): void => { ctx.addIssue({ code: "custom", path, message }); };
  if (c.tool) {
    if (!TOOL_FORMATS[c.tool].includes(c.format)) bad(["format"], `The ${c.tool} tool cannot use the ${c.format} format`);
  } else if (["toast", "inline", "feed_item", "recommendation"].includes(c.format)) {
    bad(["tool"], `The ${c.format} format needs a tool`);
  }
  const tool = toolOf(c);
  // Tool-specific blocks must match the tool: a stray block would be silently ignored, which hides mistakes.
  if (tool !== "toast" && c.toast) bad(["toast"], "Toast options only apply to the toast tool");
  if (tool !== "feed" && c.feed) bad(["feed"], "Feed options only apply to the feed tool");
  if (tool !== "upsell" && c.recommend) bad(["recommend"], "Recommendation options only apply to the upsell tool");
  if (tool !== "sms" && tool !== "email" && c.form) bad(["form"], "Form options only apply to the sms and email tools");

  if (tool === "upsell") {
    if (!c.recommend) bad(["recommend"], "Upsell campaigns need recommendation options");
    else {
      if (c.recommend.source === "manual" && c.recommend.productIds.length === 0) bad(["recommend", "productIds"], "Pick at least one product");
      if (c.recommend.source === "shipping_threshold" && c.recommend.freeShippingThreshold === undefined) bad(["recommend", "freeShippingThreshold"], "Set the free-shipping threshold");
    }
  }
  if (tool === "toast" && c.toast?.kind === "shipping_incentive" && c.toast.freeShippingThreshold === undefined) bad(["toast", "freeShippingThreshold"], "Set the free-shipping threshold");
  if (tool === "sms") {
    if (!c.form) bad(["form"], "SMS campaigns need a signup form");
    else if (!c.form.collect.phone) bad(["form", "collect", "phone"], "An SMS form must collect a phone number");
  }
  if (tool === "email" && c.format !== "restock") {
    if (!c.form) bad(["form"], "Email campaigns need a signup form");
    else if (!c.form.collect.email) bad(["form", "collect", "email"], "An email form must collect an email address");
    else {
      // Options that exist in the schema for later but are not honoured yet. Rejecting them beats silently ignoring a merchant's choice.
      if (c.form.collect.phone) bad(["form", "collect", "phone"], "Phone collection is not available on email forms: use the SMS tool for phone numbers");
      if (!c.form.doubleOptIn) bad(["form", "doubleOptIn"], "Single opt-in is not available: shoppers always confirm by email");
      // An incentive (`promotion`) is allowed: the form never draws it, and the shopper receives it only after confirming.
    }
  }
});
export type CampaignConfig = z.infer<typeof CampaignConfig>;

/** What the storefront receives: a published version of a campaign. */
export const PublishedCampaign = z.object({
  campaignId: z.string(),
  versionId: z.string(),
  config: CampaignConfig,
  /** When this version went live (ISO). Shown as a feed item's date and used to order the feed. Optional for older cached configs. */
  publishedAt: z.string().datetime().optional(),
});
export type PublishedCampaign = z.infer<typeof PublishedCampaign>;

export const StorefrontConfig = z.object({
  schemaVersion: z.literal(SCHEMA_VERSION),
  siteId: z.string(),
  generatedAt: z.string().datetime(),
  deliveryEnabled: z.boolean(),
  /** The store currency (ISO 4217), for formatting amounts such as a free-shipping gap. Optional so older cached configs stay valid. */
  currency: z.string().length(3).optional(),
  campaigns: z.array(PublishedCampaign).max(50),
});
export type StorefrontConfig = z.infer<typeof StorefrontConfig>;

export { slotOf, toolOf } from "./slots";
